def chars(s):
    """念出来的字数：汉字 + 数字（一串数字按读法粗算）+ 英文单词。"""
    n = len(re.findall(r"[一-鿿]", s))
    for num in re.findall(r"\d+", s):
        n += min(len(num) + 1, 6)
    n += len(re.findall(r"[A-Za-z]+", s))
    return n


