def cam_at(take, m):
    """主时间 m → (出镜编号, 出镜时间)，这一刻没有出镜就返回 None。"""
    for cid, lag, a, b in CAMS[take]:
        if a <= m < b:
            t = m - lag
            if 0 <= t < CAM_DUR[cid] - 1 / FPS:
                return cid, t
    return None


def to_master(src, t):
    """声音来源的时间 → 所在段的主时间。"""
    take = SRC_TAKE[src]
    if src.startswith("R") or src in VO_DUR:
        return t
    cands = [(lag, a, b) for cid, lag, a, b in CAMS[take] if cid == src]
    for lag, a, b in cands:
        m = t + lag
        if a <= m < b:
            return m
    lag, a, b = cands[0]
    return t + lag


def has_screen(take):
    return take in SCR_DUR
