def width(t):
    """字幕一行的大致宽度（按汉字计）：汉字、全角标点 1，字母 0.55，数字 0.6，空格 0.3。"""
    w = 0
    for ch in t:
        if ch == " ":
            w += 0.3
        elif ch.isascii() and ch.isalpha():
            w += 0.55
        elif ch.isascii():
            w += 0.6
        else:
            w += 1
    return w


